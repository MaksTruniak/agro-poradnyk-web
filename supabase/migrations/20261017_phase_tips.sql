-- Поради за фенофазами багаторічних культур.
-- Запускати ПІСЛЯ 20261016_perennial_plantings.sql і 20261001_admin_ai_functions.sql (потрібна public.is_admin()).
--
-- Порада прив'язана до групи культур (crop_catalog.group_key) і фенофази (growth_phases.key).
-- Фермер бачить поради поточної фази своїх насаджень (сторінка поля, нагадування) — лише опубліковані.
-- Початкові поради — ЧЕРНЕТКИ (is_published = false): їх має переглянути агроном,
-- після чого адмін редагує й публікує їх на сторінці «Поради за фазами» в адмінці.

begin;

create table if not exists public.phase_tips (
  id uuid primary key default gen_random_uuid(),
  crop_group text not null check (crop_group in ('berry_shrub', 'berry_herb', 'grape', 'fruit_pome', 'fruit_stone', 'nut')),
  phase_key text not null check (length(phase_key) between 1 and 120),
  title text not null check (length(title) between 1 and 160),
  description text not null default '' check (length(description) <= 2000),
  category text not null default 'disease'
    check (category in ('pest', 'disease', 'nutrition', 'irrigation', 'harvest', 'preparation', 'pruning')),
  urgency text not null default 'medium' check (urgency in ('high', 'medium', 'low')),
  is_published boolean not null default false,
  order_num integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists phase_tips_lookup_idx on public.phase_tips (crop_group, phase_key) where is_published;

create or replace function public.phase_tips_touch()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists phase_tips_touch on public.phase_tips;
create trigger phase_tips_touch before update on public.phase_tips
  for each row execute function public.phase_tips_touch();

alter table public.phase_tips enable row level security;

drop policy if exists "phase_tips: read published" on public.phase_tips;
create policy "phase_tips: read published" on public.phase_tips
  for select to anon, authenticated using (is_published or (select public.is_admin()));

drop policy if exists "admin: all" on public.phase_tips;
create policy "admin: all" on public.phase_tips
  for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

grant select on public.phase_tips to anon, authenticated;
grant insert, update, delete on public.phase_tips to authenticated;

